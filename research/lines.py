"""The lines True Intel shows in the Armory's passive panel: every vanilla passive row with what its value really does
(research/lines.md), the script's LINES block (between the LINES markers in true_intel.lua), and the panel's room in
every game language.

  python -B mods/TrueIntel/research/lines.py [--check]
  --check   only verify: the targets match the game data, every passive fits the panel in every language, and the
            block and lines.md are current

Inputs (the workspace's): FileDiver's plaintext mirror of the passive records
(_shared/filediver/datalibrary/generated_customization_passive_bonuses.dl_bin, layout in passive_bonuses.go), the
game's strings in its 15 languages (_research/equip_set/strings, *.strings.json: read here, never copied into the
mod) and the mod's texts (locales/*.lua). Standard library only. The decoder is Helmet Passives Reborn's
research/catalog.py (the author's own, GPL).

A line replaces one row's text id (row +0xC): the row's key, type and value stay untouched, so nothing the game uses
changes. Three kinds, each number read live from the game's memory by the script (the values below are this build's):
- stat:  a description-only row (no game code reads its key; the effect is the passive's stat row, applied at spawn).
         The line shows the stat row's number, and only where it differs from the row's own (GUNSLINGER's reload today).
- armor: the armor rating row (AFAE3B47, Add): the Armory's rating is 100 + (armor - 1) x 50 with the passive's value
         in `armor`, so the row is worth value x 50 of the rating shown (the scale is read from the game's code).
- bonus: a row whose text has no number: the line adds the game's own #BONUS of the row's value (Multiply:
         |1 - v| x 100 %; Add: the integer), so it follows the live value too.
Each line's text is a locale string (locales/en.lua and its translations); {number} is the mod's number.
"""
import glob
import json
import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MOD = HERE.parent
BSL = MOD.parents[1]
SCRIPT = MOD / 'true_intel.lua'
LOCALES = MOD / 'locales'
DATALIB = BSL / '_shared' / 'filediver' / 'datalibrary'
STRINGS = BSL / '_research' / 'equip_set' / 'strings'
BEGIN = '-- BEGIN LINES (generated by research/lines.py from the game data; do not edit)\n'
END = '-- END LINES\n'
MOD_TYPES = {0: 'Set', 1: 'Add', 2: 'Multiply', 3: 'Time'}
TYPE_IDS = {v: k for k, v in MOD_TYPES.items()}

# The game's 15 text languages: HD2Runtime's code -> (the locale tag the mod uses, the strings files' language name;
# Simplified Chinese's files carry no known name).
LANGUAGES = {'us': ('en', 'us'), 'gb': ('en-GB', 'gb'), 'bp': ('pt-BR', 'bp'), 'de': ('de', 'de'), 'es': ('es', 'es'),
             'fr': ('fr', 'fr'), 'it': ('it', 'it'), 'jp': ('ja', 'jp'), 'ko': ('ko', 'ko'), 'ms': ('es-419', 'ms'),
             'pl': ('pl', 'pl'), 'pt': ('pt', 'pt'), 'ru': ('ru', 'ru'), 'cn': ('zh-Hans', ''), 'tc': ('zh-Hant', 'tc')}
CN_HASH = '0x5942ccf7'  # Simplified Chinese's language hash (HD2Runtime's `cn`)
PERCENT, SECONDS = 0xFDAEE570, 0x96C4F2FC  # the game's #BONUS templates (#PERCENT, #SECONDS)
COLOR = '<c=ffffe900>'  # what the game puts for <c=#COLOR> (the live panel buffer, 1-recon-1)

# The Armory panel's room. Live (HPR 1-recon-7 and 11, True Intel 1-recon-1): three rows fit, 176 visible characters
# in all fit in English and 227 overflow; a formatted line goes into 255 bytes and a passive's lines into 512. In
# every language a passive True Intel changes must fit as the game's own longest passive in that language does.
PANEL = {'rows': 3, 'line_bytes': 255, 'bytes': 512}
ARMOR_KEY, ARMOR_SCALE = 0xAFAE3B47, 50.0  # the Armory's scale in this build (signature armor_scale)
ARMOR_STRING = 'line.armor'

# Description-only keys -> (the stat row that does the work, the line's string). Helmet Passives Reborn's
# passive_keys.md; HD2Runtime's ArmorPassiveCatalog agrees. Stats: 12 ammo capacity, 13 primary reload, 14 support
# reload, 15 sidearm reload, 16 sidearm draw / holster, 17 sidearm recoil.
DESCRIPTION_ONLY = {0x33C9C713: (12, 'line.ammo'), 0xCC530B21: (13, 'line.reload_primary'),
                    0x35F17BEC: (14, 'line.reload_support'), 0xB4F88129: (15, 'line.reload_sidearm'),
                    0xAD5289FE: (16, 'line.draw_sidearm'), 0x22035F3C: (17, 'line.recoil_sidearm')}

# Rows whose text gives no number, with the string of the line that adds the game's #BONUS. Each from the code that
# reads the key (decompiles in _research/true_intel/keys1.c; never copied here):
# - C8CCB6FA ergonomics (0x779250): the weapon's ergonomics + the value, capped at 100 (the stat the Armory shows as
#   ERGONOMICS; an attachment "Improves Ergonomics by 10").
# - A189ADB6 stamina on damage (0x9435F0): stamina (0-1) += (health fraction before - after) x value, capped at full.
# - 11A3C04C knockdown (0x93FD50): knocked prone when the threshold <= the hit's force x value.
# - CD79A687 / F6D67313 (0x9E94C0): the jog and sprint tiers' speeds x value (the walk tier has no key); the line
#   needs both rows to hold the same value (`same`).
BONUS_LINES = {
    0xC8CCB6FA: {'type': 'Add', 'string': 'line.ergonomics'},
    0xA189ADB6: {'type': 'Add', 'string': 'line.stamina'},
    0x11A3C04C: {'type': 'Multiply', 'string': 'line.knockdown'},
    0xCD79A687: {'type': 'Multiply', 'string': 'line.speed', 'same': 0xF6D67313},
}

# What each key's value really does, for lines.md (the research behind the verdicts).
MEANING = {
    0xAFAE3B47: 'armor rating: value x 50 of the rating the Armory shows (100 + (armor - 1) x 50, 0x1915EB0)',
    0xC8CCB6FA: 'weapon ergonomics + value, the total capped at 100 (0x779250)',
    0xA189ADB6: 'stamina += health fraction lost x value, capped at full (0x9435F0)',
    0x11A3C04C: "knockdown: the hit's force x value against the threshold (0x93FD50)",
    0xCD79A687: 'jog tier speed x value (0x9E94C0)',
    0xF6D67313: 'sprint tier speed x value (0x9E94C0; no text: OXYGENATOR\'s jog line covers it)',
    0xCB814D05: 'chance to survive = value - 1 against a uniform roll (0xB71860): the 50% is exact',
    0x0DFF0E42: 'Set 1 selects state 0x7DCD5820 instead of 0x0399532A in a state machine (0x1147C10): unnamed',
    0x8933E7F4: 'scales an element-2 status amount (HD2Runtime: likely arc stun buildup): its reader is unread',
    0x73734D67: 'flinch off while set (UNFLINCHING\'s stat 11 x0.05 also scales an integer quantity, 0x607ED0)',
}


def dlsum(name):
    r = 5381
    for c in name:
        r = (r * 33 + ord(c)) & 0xFFFFFFFF
    return (r - 5381) & 0xFFFFFFFF


def load_strings():
    """The game's strings: {code: {id: text}} for the 15 languages."""
    by_name = {name: code for code, (_, name) in LANGUAGES.items()}
    out = {code: {} for code in LANGUAGES}
    for f in sorted(glob.glob(str(STRINGS / '*.strings.json'))):
        with open(f, encoding='utf-8') as fh:
            d = json.load(fh)
        lang = d.get('Language')
        if not isinstance(lang, dict):
            continue
        code = by_name.get(lang.get('KnownName'))
        if code == 'cn' and str(lang.get('Hash')).lower() != CN_HASH:
            code = None
        if code is None:
            continue
        for it in d.get('Items', []):
            if it['Value']:
                out[code].setdefault(it['Key'], it['Value'])
    return out


def load_english():
    return load_strings()['us']


def dl_items(path, type_name):
    """generated_*.dl_bin: u32 count, then per item a 24-byte LDLD header (magic, version, type, size, 8 bytes)."""
    data = Path(path).read_bytes()
    count = struct.unpack_from('<I', data, 0)[0]
    pos, want = 4, dlsum(type_name)
    for _ in range(count):
        magic, _version, typ, size = struct.unpack_from('<4sIII', data, pos)
        if magic != b'LDLD' or typ != want:
            sys.exit(f'{path}: unexpected item header at {pos}')
        yield data[pos + 24:pos + 24 + size]
        pos += 24 + size


def decode_passives(text):
    passives = {}
    for body in dl_items(DATALIB / 'generated_customization_passive_bonuses.dl_bin',
                         'HelldiverCustomizationPassiveBonusSettings'):
        pid, name, _icon, m_off, m_cnt, s_off, s_cnt, _tag = struct.unpack_from('<IIQqqqqI', body, 0)
        rows = []
        for j in range(m_cnt):
            key, mtype, value, desc = struct.unpack_from('<IIfI', body, m_off + 16 * j)
            rows.append({'key': key, 'type': MOD_TYPES.get(mtype, mtype), 'value': value, 'text_id': desc,
                         'text': text.get(desc)})
        stats = {}
        for j in range(s_cnt):
            stat, add, mul = struct.unpack_from('<Iff', body, s_off + 12 * j)
            stats[stat] = {'add': add, 'mul': mul}
        passives[pid] = {'id': pid, 'name': text.get(name) or '?', 'rows': rows, 'stats': stats}
    return passives


def parse_locale(path):
    """A locale file's language and strings (the plain data the translation kit allows)."""
    src = path.read_text(encoding='utf-8')
    language = re.search(r"^\s*language\s*=\s*'([^']*)'", src, re.M)
    strings = {}
    for key, raw in re.findall(r"\['([\w.\-]+)'\]\s*=\s*'((?:[^'\\]|\\.)*)'", src.split('strings', 1)[1]
                               .split('\n    }', 1)[0]):
        strings[key] = re.sub(r'\\(.)', r'\1', raw)
    return {'language': language.group(1) if language else None, 'strings': strings}


def load_locales():
    """{tag: strings}, English under 'en'."""
    out = {}
    for path in sorted(LOCALES.glob('*.lua')):
        loc = parse_locale(path)
        if loc['language'] != path.stem:
            sys.exit(f'{path.name}: language {loc["language"]!r}')
        out[path.stem] = loc['strings']
    return out


def resolve(locales, tag):
    """The texts for a tag: English, then its base language's, then its own (bingus_text's order)."""
    texts = dict(locales['en'])
    base = tag.split('-')[0]
    for t in ([base, tag] if base != tag else [tag]):
        if t != 'en':
            texts.update(locales.get(t, {}))
    return texts


def pct(v):
    """The game's Multiply #BONUS: |1 - v| x 100, as a whole percent."""
    return round(abs(1 - v) * 100)


def bonus(row, templates=None):
    """What the game's formatter puts for #BONUS (Set/Add: the integer; Multiply: the percent; Time: seconds), in a
    language's templates ({PERCENT, SECONDS: text}; English without)."""
    t, v = row['type'], row['value']
    templates = templates or {PERCENT: '#PERCENT%', SECONDS: '#SECONDSs'}
    if t == 'Multiply':
        return templates[PERCENT].replace('#PERCENT', '%d' % pct(v))
    if t == 'Time':
        return templates[SECONDS].replace('#SECONDS', '%.1f' % v)
    return '%d' % int(v)


def fill(text, row, templates=None, number=None):
    """A line as the game formats it: #SIGN / #BONUS / {number} filled in (the colour tags kept)."""
    s = text or ''
    if number is not None:
        s = s.replace('{number}', str(number))
    if row is not None:
        s = s.replace('#SIGN', '+' if row['value'] >= 0 else '-').replace('#BONUS', bonus(row, templates))
    return s


def visible(text, row=None, templates=None, number=None):
    """The line as the panel shows it: colour tags gone."""
    return re.sub(r'</?c[^>]*>', '', fill(text, row, templates, number))


def line_bytes(text, row=None, templates=None, number=None):
    """The formatted line's bytes, as in the panel's buffer."""
    return len(fill(text, row, templates, number).replace('<c=#COLOR>', COLOR).encode('utf-8'))


def slug(passive_id, key):
    return 'p%d_%08x' % (passive_id, key)


def targets(passives, english=None):
    """Every line True Intel may show: [(passive, row, entry)] in passive id order. `english` (locales/en.lua's
    strings) is checked: a stat line's English is the game's own line with the true number."""
    out = []
    for pid in sorted(passives):
        p = passives[pid]
        keys = {r['key']: r for r in p['rows']}
        for r in p['rows']:
            k = r['key']
            e = None
            if k in DESCRIPTION_ONLY and r['text']:
                stat_id, string = DESCRIPTION_ONLY[k]
                stat = p['stats'].get(stat_id)
                if stat is None:
                    sys.exit(f"{p['name']}: description-only row {k:08X} without its stat row")
                if stat['add'] != 0:
                    sys.exit(f"{p['name']}: stat {stat_id} has an add ({stat['add']}): not a percent")
                if english is not None and english.get(string) != r['text'].replace('#BONUS', '{number}%'):
                    sys.exit(f"{p['name']}: {string} in en.lua is not the game's line with {{number}}%: "
                             f"{english.get(string)!r}")
                e = {'kind': 'stat', 'stat': stat_id, 'string': string, 'number': pct(stat['mul']),
                     'listed': pct(r['value']), 'shown': pct(stat['mul']) != pct(r['value'])}
            elif k == ARMOR_KEY:
                if r['type'] != 'Add':
                    sys.exit(f"{p['name']}: armor rating row is {r['type']}")
                e = {'kind': 'armor', 'string': ARMOR_STRING, 'number': round(r['value'] * ARMOR_SCALE),
                     'shown': True}
            elif k in BONUS_LINES:
                b = BONUS_LINES[k]
                if r['type'] != b['type']:
                    sys.exit(f"{p['name']}: row {k:08X} is {r['type']}, the line expects {b['type']}")
                same = b.get('same')
                if same is not None and (same not in keys or keys[same]['value'] != r['value']):
                    sys.exit(f"{p['name']}: row {k:08X} expects row {same:08X} with the same value")
                e = {'kind': 'bonus', 'string': b['string'], 'same': same, 'number': None, 'shown': True}
            if e:
                if not r['text_id']:
                    sys.exit(f"{p['name']}: row {k:08X} has no text to replace")
                if english is not None and e['string'] not in english:
                    sys.exit(f"{e['string']} is not in locales/en.lua")
                e['key'] = slug(pid, k)
                out.append((p, r, e))
    return out


def rendered(p, r, e, texts, templates=None):
    """A target's line as the panel shows it, from one language's texts."""
    return visible(texts[e['string']], r, templates, e['number'])


def templates_of(strings, code):
    return {PERCENT: strings[code][PERCENT], SECONDS: strings[code][SECONDS]}


def budget(passives, chosen, strings, locales):
    """Problems with each passive True Intel changes, in every language, against the panel's room; and per language
    {code: (the game's longest passive in visible characters, ours, our longest formatted line in bytes)}."""
    problems, room = [], {}
    by_row = {(p['id'], r['key']): (p, r, e) for p, r, e in chosen if e['shown']}
    for code, (tag, _) in LANGUAGES.items():
        texts, tpl, game = resolve(locales, tag), templates_of(strings, code), strings[code]
        game_most = max(sum(len(visible(game.get(r['text_id']), r, tpl)) for r in p['rows'] if r['text_id'])
                        for p in passives.values())
        ours_most, bytes_most = 0, 0
        for pid in sorted(passives):
            p = passives[pid]
            if not any((pid, r['key']) in by_row for r in p['rows']):
                continue
            sizes, total_bytes, rows = [], 0, 0
            for r in p['rows']:
                if not r['text_id']:
                    continue
                rows += 1
                t = by_row.get((pid, r['key']))
                if t:
                    text, number = texts[t[2]['string']], t[2]['number']
                else:
                    text, number = game.get(r['text_id']), None
                n, b = len(visible(text, r, tpl, number)), line_bytes(text, r, tpl, number)
                sizes.append(n)
                total_bytes += b + 1
                if t:
                    bytes_most = max(bytes_most, b)
                    if b >= PANEL['line_bytes']:
                        problems.append(f"{code} {p['name']}: {b} bytes formatted (the game's line buffer: 255)")
            ours_most = max(ours_most, sum(sizes))
            if rows > PANEL['rows']:
                problems.append(f"{code} {p['name']}: {rows} rows (panel: {PANEL['rows']})")
            if sum(sizes) > game_most:
                problems.append(f"{code} {p['name']}: {sum(sizes)} visible characters, more than the game's longest "
                                f"passive in this language ({game_most})")
            if total_bytes >= PANEL['bytes']:
                problems.append(f"{code} {p['name']}: {total_bytes} bytes (the panel's buffer: 512)")
        room[code] = (game_most, ours_most, bytes_most)
    return problems, room


def lua_string(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def lua_block(chosen):
    out = [BEGIN, '-- kind: stat (the stat row\'s number, shown only where it differs from the row\'s), armor (the row\'s '
           'value x the\n-- Armory\'s scale), bonus (the game\'s #BONUS of the row). `text` is the vanilla text id, '
           '`value` this build\'s\n-- value, `string` the line\'s text in locales/.\n',
           'local LINES = {\n']
    for p, r, e in chosen:
        second = f"     text = 0x{r['text_id']:08X}, kind = '{e['kind']}'"
        if e['kind'] == 'stat':
            second += f", stat = {e['stat']}"
        if e.get('same') is not None:
            second += f", same = 0x{e['same']:08X}"
        second += f", string = '{e['string']}'}},"
        out.append(f"    {{key = '{e['key']}', passive = {p['id']}, name = {lua_string(p['name'])}, "
                   f"row = 0x{r['key']:08X}, type = {TYPE_IDS[r['type']]}, value = {r['value']:.6g},\n{second}\n")
    out.append('}\n')
    out.append(END)
    return ''.join(out)


def markdown(passives, chosen, english, room):
    by_row = {(p['id'], r['key']): e for p, r, e in chosen}
    lines = ['# True Intel: the lines (game build 25480438)', '',
             'Generated by `research/lines.py` from the passive records (FileDiver\'s plaintext mirror), the game\'s '
             'strings and `locales/`. Each row: the key, its type and value, what the Armory says in English, and the '
             'line True Intel shows (**bold**), or why the game\'s line stays. The script reads every number live; '
             'these are this build\'s.', '', '| passive | row | the Armory says | True Intel |', '| --- | --- | --- | --- |']
    for pid in sorted(passives):
        p = passives[pid]
        for r in p['rows']:
            e = by_row.get((pid, r['key']))
            row = f"`{r['key']:08X}` {r['type']} {r['value']:g}"
            says = visible(r['text'], r) if r['text_id'] else '(no text)'
            if e and e['shown']:
                verdict = '**' + rendered(p, r, e, english) + '**'
                if e['kind'] == 'stat':
                    verdict += f" (stat {e['stat']} x{p['stats'][e['stat']]['mul']:g})"
            elif e:
                verdict = f"exact (stat {e['stat']} x{p['stats'][e['stat']]['mul']:g}); watched: a line only if they " \
                          "differ"
            elif r['key'] in MEANING:
                verdict = 'stays: ' + MEANING[r['key']]
            elif not r['text_id']:
                verdict = 'stays hidden: meaning not researched'
            elif '#BONUS' in (r['text'] or ''):
                verdict = 'exact (the game shows the row\'s own value)'
            else:
                verdict = 'stays'
            lines.append(f"| {p['name']} | {row} | {says} | {verdict} |")
    shown = [t for t in chosen if t[2]['shown']]
    lines += ['', f'{len(shown)} lines shown today, {len(chosen) - len(shown)} watched (description-only rows that '
              'match their stat row).', '', '## The panel\'s room by language', '',
              'Visible characters of the longest passive True Intel changes, against the game\'s own longest passive '
              'in the same language (which fits), and the longest formatted line in bytes (the game\'s line buffer '
              'holds 254).', '', '| language | locale | the game\'s longest | True Intel\' longest | longest line (bytes) |',
              '| --- | --- | --- | --- | --- |']
    for code, (tag, _) in LANGUAGES.items():
        g, o, b = room[code]
        lines.append(f'| {code} | {tag} | {g} | {o} | {b} |')
    lines.append('')
    return '\n'.join(lines)


def main():
    strings = load_strings()
    locales = load_locales()
    passives = decode_passives(strings['us'])
    chosen = targets(passives, locales['en'])
    problems, room = budget(passives, chosen, strings, locales)
    for x in problems:
        print('BUDGET:', x)
    block = lua_block(chosen)
    script = SCRIPT.read_text(encoding='utf-8')
    if BEGIN not in script or END not in script:
        sys.exit('true_intel.lua has no LINES markers')
    head, rest = script.split(BEGIN, 1)
    current_body, tail = rest.split(END, 1)
    md = markdown(passives, chosen, locales['en'], room)
    for p, r, e in chosen:
        print('%-26s %-9s %-5s %s' % (p['name'], '%08X' % r['key'], e['kind'],
                                      rendered(p, r, e, locales['en']) if e['shown'] else '(exact: watched)'))
    for code, (g, o, b) in room.items():
        print('%-3s game %3d, ours %3d, line %3d bytes' % (code, g, o, b))
    if '--check' in sys.argv:
        stale = []
        if BEGIN + current_body + END != block:
            stale.append('the LINES block in true_intel.lua')
        if not (HERE / 'lines.md').exists() or (HERE / 'lines.md').read_text(encoding='utf-8') != md:
            stale.append('research/lines.md')
        for s in stale:
            print('STALE:', s)
        sys.exit(1 if stale or problems else 0)
    SCRIPT.write_text(head + block + tail, encoding='utf-8', newline='\n')
    (HERE / 'lines.md').write_text(md, encoding='utf-8', newline='\n')
    print(f'{len(chosen)} lines written to {SCRIPT.name} and research/lines.md')
    sys.exit(1 if problems else 0)


if __name__ == '__main__':
    main()
