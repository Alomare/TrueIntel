"""The game's loading screen tips: their text ids from the game.dll dump -> the script's TIPS block.

The tips are a static array of 82 u32 text ids in game.dll's read-only data, five identical copies in this build
(RESEARCH.md "Loading screen tips"). This lists them with their English text and each language's longest tip (the
room our tips should keep to), checks the copies, and writes the ids between the TIPS markers of true_intel.lua.

Usage (from the workspace root): python -B mods/TrueIntel/research/tips.py [--check]
  --check   only verify the script's block is current (exit 1 otherwise)
"""
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MOD = HERE.parent
BSL = MOD.parents[1]
sys.path.insert(0, str(HERE))
import lines as research  # noqa: E402

SCRIPT = MOD / 'true_intel.lua'
DUMP = BSL / '_research' / 'game_25480438.dll'
FIRST = 0x21F0D00  # the first copy in build 25480438
COUNT = 82
BEGIN = '-- BEGIN TIPS (generated by research/tips.py from the game data; do not edit)\n'
END = '-- END TIPS\n'
# The jokes and lore among the game's tips (the author: "aim to replace the jokes"), by the start of their English
# text; each must match exactly one tip. The rest are real advice and stay.
JOKES = [
    'Did you know tips are shown', "Don't drink and drive", 'Super Earth has many holidays', "Friendly Fire isn't",
    'Helldivers traveling the galaxy might come across', 'When you\'re up against the bots, remember the 3 Cs',
    "Don't die!", "Don't worry—stims have zero addictive", 'Managed Democracy is a cornerstone',
    'Want to show off how firmly you support capitalism', "If at first you don't succeed, dive",
    'Pay attention to these tips', "Don't worry, if you fail an objective", "Don't forget to take breaks",
    'Practice your daily desensitization', 'Remember to fill in your C-01 permit', 'The Galactic War is a united effort',
    "You are Super Earth's elite", 'Remember: Freedom!', 'When in doubt, don\'t think', 'Super Earth recommends spending',
    'If you notice a squadmate sympathizing', 'Every citizen is equally important', "Don't panic.",
    'If an enemy ever attempts to engage in diplomacy', 'The Ministry of Science', 'The Ministry of Defense',
    'The Ministry of Expansion', 'The Ministry of Prosperity', 'The Ministry of Truth', 'The Ministry of Humanity',
    'The Ministry of Unity',
]


def jokes(ids, english):
    """The ids of the joke tips; exits when a JOKES entry matches no tip or several."""
    out = set()
    for start in JOKES:
        hits = [i for i in ids if english.get(i, '').startswith(start)]
        if len(hits) != 1:
            sys.exit('JOKES entry %r matches %d tips' % (start, len(hits)))
        out.add(hits[0])
    return out


def tip_ids(dump):
    return list(struct.unpack_from('<%dI' % COUNT, dump, FIRST))


def copies(dump, ids):
    """Every RVA where the whole array sits (the dump's offsets are RVAs)."""
    blob, out, at = struct.pack('<%dI' % COUNT, *ids), [], 0
    while True:
        at = dump.find(blob, at)
        if at < 0:
            return out
        out.append(at)
        at += 4


def lua_block(ids, english):
    joke = jokes(ids, english)
    out = [BEGIN, '-- The game\'s %d loading screen tips (text ids, in the array\'s order), with their English text;\n'
           % len(ids), '-- TIP_JOKES: the %d jokes and lore among them (the slots our tips take).\n' % len(joke),
           'local VANILLA_TIPS = {\n']
    for i in ids:
        text = english.get(i, '?').replace('\n', ' / ')
        out.append('    0x%08X,  -- %s%s\n' % (i, 'joke: ' if i in joke else '',
                                             text[:100] + ('...' if len(text) > 100 else '')))
    out.append('}\n')
    out.append('local TIP_JOKES = {%s}\n' % ', '.join('[0x%08X] = true' % i for i in ids if i in joke))
    out.append(END)
    return ''.join(out)


def main():
    dump = DUMP.read_bytes()
    strings = research.load_strings()
    ids = tip_ids(dump)
    missing = [i for i in ids if i not in strings['us']]
    if missing:
        sys.exit('not text ids: ' + ', '.join('%08X' % i for i in missing))
    where = copies(dump, ids)
    print('%d tips; copies at %s' % (len(ids), ', '.join('0x%X' % a for a in where)))
    for code in research.LANGUAGES:
        longest = max(len(strings[code].get(i, '')) for i in ids)
        print('  %s: longest tip %d characters' % (code, longest))
    block = lua_block(ids, strings['us'])
    script = SCRIPT.read_text(encoding='utf-8')
    if BEGIN not in script or END not in script:
        sys.exit('no TIPS markers in ' + SCRIPT.name)
    head, rest = script.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + block + tail
    if '--check' in sys.argv:
        stale = new != script
        print('STALE: the TIPS block' if stale else 'TIPS block current')
        sys.exit(1 if stale else 0)
    SCRIPT.write_text(new, encoding='utf-8', newline='\n')
    print('written to', SCRIPT.name)


if __name__ == '__main__':
    main()
