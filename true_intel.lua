-- Logging and status

local function open_log(name)
    if loader and type(loader.open_log) == 'function' then
        local ok, f = pcall(loader.open_log, name)
        if ok then return f end
    end
end

local log_file = open_log('TrueIntel.log')
local log_lines = 0

local function note(msg)
    if not log_file or log_lines >= LOG_LINES then return end
    log_lines = log_lines + 1
    pcall(function()
        log_file:write(string.format('[f%d t%.1f] %s\n', M.frames, M.time, msg))
        log_file:flush()
    end)
end

local once = {}
local function note_change(key, msg)  -- logs msg when it differs from the last one under key
    if once[key] == msg then return end
    once[key] = msg
    note(msg)
end

local status = {verdict = 'STARTING', details = {}}
local function write_status()
    local f = open_log('TrueIntel_STATUS.log')
    if not f then return end
    local lines = {status.verdict, NAME .. ' V' .. M.version}
    for _, l in ipairs(status.details) do lines[#lines + 1] = l end
    pcall(function()
        f:write(table.concat(lines, '\n') .. '\n')
        f:close()
    end)
end

