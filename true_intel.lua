-- Frame step

local function retire(verdict)
    M.retired = true
    if lines.state == 'applied' or lines.state == 'text lost' then
        lines.state = 'retired'
        pcall(swap_all, 'retired')
    end
    status.verdict = verdict
    write_status()
end

local function start()
    M.started = true
    if not float_selftest() then
        note('Float decoding self-test failed')
        return retire('NOT AVAILABLE - float self-test failed; the game is unchanged')
    end
    local ok, why = init_native()
    if not ok then
        note('Native access unavailable: ' .. why)
        return retire('NOT AVAILABLE - ' .. why .. '; the game is unchanged')
    end
    local okr, rwhy = runtime_start()
    if not okr then
        runtime.why = rwhy
        note('Not available: ' .. tostring(rwhy))
        return retire('NOT AVAILABLE - ' .. tostring(rwhy) .. '; the game is unchanged')
    end
    code = sigscan.new(SIGS, read, native.base)
    local all, reason = code:start()
    if all == nil then
        note('Signatures not available: ' .. tostring(reason))
        return retire('NOT AVAILABLE - signatures: ' .. tostring(reason) .. '; the game is unchanged')
    elseif all then
        local okv, missing = finish_resolution()
        if not okv then return retire('NOT AVAILABLE - signatures missing: ' .. missing .. '; the game is unchanged') end
    else
        note('Searching game.dll for moved code (game updated?)')
    end
    status.verdict = 'WORKING'
    update_status()
end

local function frame(dt)
    M.frames = M.frames + 1
    if not M.started then return start() end
    if not M.ready then
        if code.scan and code:step() then
            local okv, missing = finish_resolution()
            if not okv then retire('NOT AVAILABLE - signatures missing: ' .. missing .. '; the game is unchanged') end
        end
        return
    end
    local before = lines.state
    lines_step()
    if lines.state ~= before or M.frames % 1800 == 0 then update_status() end
end

local function guarded(step, where, ...)
    local args = {...}
    local ok, err = xpcall(function() return step(unpack(args)) end, debug.traceback)
    if not ok then
        M.errors = M.errors + 1
        note('Error (' .. where .. '): ' .. tostring(err))
        if M.errors >= 10 then retire('STOPPED - repeated errors; the game\'s texts are back (see TrueIntel.log)') end
    end
end

local original_update = rawget(_G, 'update')
update = function(dt, ...)
    M.time = M.time + (tonumber(dt) or 0)
    if not M.retired then guarded(frame, 'update', tonumber(dt) or 0) end
    if type(original_update) == 'function' then return original_update(dt, ...) end
end

note(NAME .. ' V' .. M.version .. ' loaded')
M._test = {lines = lines, signature_values = function() return V end}
return M
