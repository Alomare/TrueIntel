-- The passive tables (the customization manager): {manager, count, records (id -> address)}, or nil, why and whether
-- the tables are wrong (not just not there yet). Helmet Passives Reborn adds records (39): any count is read.
local function passive_tables()
    local m = read_pointer(native.base + V.customization)
    if not m then return nil, 'no customization manager yet' end
    local head = read(m, V.passive_index + PASSIVE.ids * 4)
    if not head then return nil, 'manager unreadable' end
    local list_at, count = pointer(head, V.passives), u32(head, V.passives + 8)
    if not list_at or not count or count == 0 then return nil, 'passive array unset' end
    if count > 64 then return nil, string.format('%d passive records', count), true end
    local list = read(list_at, count * 8)
    if not list then return nil, 'passive array unreadable' end
    local records = {}
    for id = 0, PASSIVE.ids - 1 do
        local i = u32(head, V.passive_index + id * 4)
        if i ~= 0xFFFFFFFF then
            if i >= count then
                return nil, string.format('passive %d: index %d past the count %d', id, i, count), true
            end
            local r = pointer(list, i * 8)
            if not r or read32(r) ~= id then
                return nil, string.format('passive %d: record at index %d is not it', id, i), true
            end
            records[id] = r
        end
    end
    return {manager = m, count = count, records = records}
end

-- A record's modifier rows and stat rows: {rows = {{at, key, type, bits, value, text}}, stats = {[stat] = {add, mul}}},
-- or nil and why.
local function record_rows(r)
    local head = read(r, PASSIVE.record)
    if not head then return nil, 'record unreadable' end
    local out = {rows = {}, stats = {}}
    local rows_at, n = pointer(head, V.rows), u32(head, V.row_count)
    if n and n > 0 then
        if not rows_at or n > PASSIVE.most_rows then return nil, string.format('%s rows', tostring(n)) end
        local blob = read(rows_at, n * PASSIVE.row)
        if not blob then return nil, 'rows unreadable' end
        for i = 0, n - 1 do
            local o = i * PASSIVE.row
            out.rows[#out.rows + 1] = {at = rows_at + o, key = u32(blob, o), type = u32(blob, o + 4),
                                       bits = u32(blob, o + 8), value = f32(blob, o + 8), text = u32(blob, o + 12)}
        end
    end
    local stats_at, sn = pointer(head, V.stat_rows), u32(head, V.stat_row_count)
    if sn and sn > 0 then
        if not stats_at or sn > PASSIVE.most_stats then return nil, string.format('%s stat rows', tostring(sn)) end
        local blob = read(stats_at, sn * PASSIVE.stat)
        if not blob then return nil, 'stat rows unreadable' end
        for i = 0, sn - 1 do
            local o = i * PASSIVE.stat
            out.stats[u32(blob, o)] = {add = f32(blob, o + 4), mul = f32(blob, o + 8)}
        end
    end
    return out
end

local function find_row(rows, key)
    for _, row in ipairs(rows) do
        if row.key == key then return row end
    end
end

-- The game's Multiply #BONUS as a whole percent: |1 - v| x 100.
local function pct(v) return math.floor(math.abs(1 - v) * 100 + 0.5) end

-- The Armory's armor rating scale (a float in the game's code): the number, or nil.
local function armor_scale()
    if not V.armor_scale then return nil end
    local s = f32(read(native.base + V.armor_scale, 4))
    if not s or s ~= s or s <= 0 or s > 1000 then return nil end
    return s
end

-- A line's text in every language, its {number} filled in: {default, us, gb, ...} as HD2Runtime takes it.
local function line_values(spec, number, texts)
    local values = {}
    for _, l in ipairs(LANGUAGES) do
        values[l[1]] = T.format(texts[l[1]][spec.string], {number = number})
    end
    values.default = values.us
    return values
end

-- One line from the live records: {spec, row, value, number, values, key}, or nil, why and whether the game's text
-- already says it (exact, no line needed).
local function make_line(spec, p, texts)
    local r = p.records[spec.passive]
    if not r then return nil, 'no record ' .. spec.passive end
    local rec, why = record_rows(r)
    if not rec then return nil, why end
    local row = find_row(rec.rows, spec.row)
    if not row then return nil, string.format('no row %08X', spec.row) end
    if row.type ~= spec.type then return nil, string.format('row type %d (expected %d)', row.type, spec.type) end
    if row.text ~= spec.text then return nil, string.format('text id %08X (another mod\'s?)', row.text) end
    local L = {spec = spec, row = row.at, value = row.value}
    if spec.kind == 'stat' then
        local stat = rec.stats[spec.stat]
        if not stat then return nil, 'no stat row ' .. spec.stat end
        if stat.add ~= 0 then return nil, string.format('stat %d adds %g (not a percent)', spec.stat, stat.add) end
        if not (stat.mul > 0 and stat.mul < 10 and row.value > 0 and row.value < 10) then
            return nil, string.format('stat %d x%s, row %s: out of range', spec.stat, tostring(stat.mul),
                                      tostring(row.value))
        end
        L.number, L.stat_mul = pct(stat.mul), stat.mul
        local stated = pct(row.value)  -- the number the game's line states
        if L.number == stated then
            return nil, string.format('exact: %d%% (stat %d x%g)', L.number, spec.stat, stat.mul), true
        end
        L.key = spec.key .. '_' .. L.number
    elseif spec.kind == 'armor' then
        local scale = lines.scale
        if not scale then return nil, 'no armor rating scale (signature armor_scale)' end
        if not (row.value > 0 and row.value < 10) then return nil, 'armor rating row ' .. tostring(row.value) end
        L.number = math.floor(row.value * scale + 0.5)
        L.key = spec.key .. '_' .. L.number
    else
        if spec.same then
            local same = find_row(rec.rows, spec.same)
            if not same or same.bits ~= row.bits then
                return nil, string.format('row %08X differs from %08X (%s vs %s)', spec.same, spec.row,
                                          tostring(same and same.value), tostring(row.value))
            end
        end
        L.key = spec.key
    end
    L.values = line_values(spec, L.number, texts)
    return L
end

-- HD2Runtime's development text module and its write-capable adapter, once: the module, or nil after logging why.
local TEXT_API = {'handle', 'ensure', 'resolves', 'id_bytes'}
local function text_module()
    if lines.texts ~= nil then return lines.texts or nil end
    local ok, t = pcall(require, 'hd2runtime/runtime/text_resources')
    local okw, w = pcall(require, 'hd2runtime/runtime/windows_write')
    local why = nil
    if not ok or type(t) ~= 'table' then
        why = 'no text module (' .. tostring(t) .. ')'
    elseif not (okw and type(w) == 'table' and type(w.create) == 'function') then
        why = 'no write adapter (' .. tostring(w) .. ')'
    else
        for _, f in ipairs(TEXT_API) do
            if type(t[f]) ~= 'function' then why = why or ('the text module has no ' .. f) end
        end
    end
    local adapter = nil
    if not why then
        local okc, a = pcall(w.create)
        if okc and type(a) == 'table' then adapter = a else why = 'the write adapter failed (' .. tostring(a) .. ')' end
    end
    if why then
        lines.texts = false
        note(string.format('Texts: HD2Runtime %s refused (%s)', tostring(runtime.hd2 and runtime.hd2.version), why))
        return nil, why
    end
    lines.texts, lines.adapter = t, adapter
    return t
end

-- Our texts as HD2Runtime handles, once per line (every language in one handle).
local function define_texts(t)
    for _, L in ipairs(lines.list) do
        L.handle = t.handle(L.key, L.values, MOD_ID)
        L.id = u32(t.id_bytes(L.handle))
        lines.ours[L.id] = true
    end
    tips_define(t)
end

-- Codes from HD2Runtime's ensure that pass (the registry not ready, or changed under it): tried again. The language
-- word holds no language for a few seconds at the game's start (Helmet Passives Reborn 1-recon-6).
local TEXT_PASSING = {UNAVAILABLE = true, REGISTRY_CHANGED = true, TARGET_UNAVAILABLE = true,
                      UNSUPPORTED_LANGUAGE = true}

-- Registers our texts (or confirms them): true, or false, why and whether the refusal may pass.
local function texts_register()
    local t, twhy = text_module()
    if not t then return false, 'texts: ' .. tostring(twhy or 'refused earlier'), false end
    local ok, done, info, why = pcall(t.ensure, lines.adapter)
    if not ok then return false, 'ensure: ' .. tostring(done), true end  -- a table that read inconsistently
    if not done then
        return false, string.format('ensure refused (%s: %s)', tostring(info), tostring(why)), TEXT_PASSING[info] == true
    end
    lines.text_misses = 0
    note(string.format('Texts: %s, table %s of %s (language %s)', tostring(info.action), tostring(info.index),
                       tostring(info.count or info.index), tostring(info.language)))
    return true
end

-- The text id a line's row should hold now: ours while our texts are registered, else the game's.
local function wanted(L)
    if lines.state ~= 'applied' then return L.spec.text end
    return L.id
end

-- Every line's row to the text id it should hold (only over the game's id or one of ours). Returns the counts.
local function swap_all(why)
    local s = {written = 0, same = 0, foreign = 0, failed = 0}
    for _, L in ipairs(lines.list) do
        local want, now = wanted(L), read32(L.row + 12)
        if now == want then
            s.same = s.same + 1
            L.state = want == L.spec.text and 'vanilla' or 'ours'
        elseif now ~= L.spec.text and not lines.ours[now] then
            s.foreign = s.foreign + 1
            if L.state ~= 'foreign' then
                L.state = 'foreign'
                note(string.format('Line %s (%s): the row holds %s, not ours nor the game\'s: left alone', L.key,
                                   L.spec.name, now and string.format('%08X', now) or 'nothing readable'))
            end
        elseif write(L.row + 12, u32_bytes(want)) and read32(L.row + 12) == want then
            s.written = s.written + 1
            L.state = want == L.spec.text and 'vanilla' or 'ours'
        else
            s.failed = s.failed + 1
            L.state = 'failed'
        end
    end
    if s.written > 0 or s.failed > 0 or s.foreign > 0 then
        note(string.format('Rows (%s): %d written, %d already set, %d held by something else, %d failed', why,
                           s.written, s.same, s.foreign, s.failed))
    end
    tips_sync(why)
    return s
end

local function lines_fail(why)
    lines.state, lines.why = 'failed', why
    note('Lines NOT applied: ' .. tostring(why) .. ' (the Armory keeps the game\'s texts)')
end

-- Making the lines (the live records, our texts), then watching (our texts, the rows, the live values).
local function lines_step()
    if lines.state ~= 'waiting' and lines.state ~= 'applied' and lines.state ~= 'text lost' then return end
    if lines.state == 'waiting' then
        if M.time < lines.retry_at then return end
        lines.retry_at = M.time + PASSIVE.retry
        lines.tries = lines.tries + 1
        if #lines.list == 0 then
            local p, why, wrong = passive_tables()
            if not p then
                lines.why = why
                if wrong or lines.tries >= PASSIVE.tries then return lines_fail(why) end
                return note_change('lines wait', 'Lines: waiting for the passive tables (' .. why .. ')')
            end
            lines.scale = armor_scale()
            note(string.format('Passive tables: %d records; armor rating scale %s', p.count, tostring(lines.scale)))
            local okt, texts = pcall(language_texts)
            if not okt then return lines_fail('locales: ' .. tostring(texts)) end
            local exact = 0
            for _, spec in ipairs(LINES) do
                local L, lwhy, is_exact = make_line(spec, p, texts)
                if L then
                    L.state = 'made'
                    lines.list[#lines.list + 1] = L
                    note(string.format('Line %s (%s, %s): "%s"', L.key, spec.name, spec.kind, L.values.us))
                else
                    if is_exact then exact = exact + 1 end
                    note(string.format('No line for %s (%s %08X): %s', spec.name, spec.kind, spec.row, lwhy))
                end
            end
            note(string.format('Lines: %d made, %d exact already, %d skipped', #lines.list, exact,
                               #LINES - #lines.list - exact))
            if #lines.list == 0 then
                lines.state, lines.why = 'idle', 'no line to show'
                return
            end
            local t, twhy = text_module()
            if not t then return lines_fail('texts: ' .. tostring(twhy)) end
            local ok, err = pcall(define_texts, t)
            if not ok then return lines_fail('texts refused: ' .. tostring(err)) end
        end
        local ok, why, passing = texts_register()
        if not ok then
            if passing and lines.tries < PASSIVE.tries then
                lines.why = why
                return note_change('lines wait', 'Lines: waiting for the text registry (' .. why .. ')')
            end
            return lines_fail(why)
        end
        lines.state, lines.why = 'applied', nil
        lines.rows_at, lines.text_at = M.time, M.time
        local s = swap_all('applied')
        note(string.format('Lines applied: %d of %d rows hold our text', s.written + s.same, #lines.list))
        return
    end
    -- Our texts: lost when the game rebuilt its registry (a language change) and nobody registered them again. A row
    -- with our id and no table would show an empty line, so the game's ids go back until they are registered again.
    if M.time - lines.text_at >= PASSIVE.text_every then
        lines.text_at = M.time
        local ok, done, code_ = pcall(lines.texts.resolves, lines.adapter, lines.list[1].handle)
        if ok and done then
            lines.text_misses = 0
            if lines.state == 'text lost' then
                lines.state = 'applied'
                swap_all('texts back')
                note('Texts: registered again (by another mod)')
            end
        elseif ok and (code_ == 'NOT_REGISTERED' or code_ == 'VERIFY_FAILED') then
            lines.text_misses = lines.text_misses + 1
            lines.text_lost_at = lines.text_lost_at or M.time
            if lines.text_misses >= 2 then  -- the same over two checks: no registration under way
                local reg, why, passing = texts_register()
                if reg then
                    note(string.format('Texts: not in the registry (%s) for %.2f s; registered again', tostring(code_),
                                       M.time - lines.text_lost_at))
                    lines.text_lost_at, lines.text_misses = nil, 0
                    if lines.state == 'text lost' then lines.state = 'applied'; swap_all('texts back') end
                else
                    note_change('texts lost', 'Texts: not in the registry (' .. tostring(code_) .. '); registering '
                                .. 'them again refused: ' .. tostring(why))
                    if lines.state == 'applied' then
                        lines.state, lines.why = 'text lost', why
                        swap_all('our texts are not registered')
                    end
                    if not passing then return lines_fail(why) end
                end
            end
        end
    end
    -- The rows: still ours, and the live values as when the lines were made.
    if M.time - lines.rows_at >= PASSIVE.rows_every then
        lines.rows_at = M.time
        swap_all('check')
        local p = passive_tables()
        for _, L in ipairs(lines.list) do
            local r = p and p.records[L.spec.passive]
            local rec = r and record_rows(r)
            local row = rec and find_row(rec.rows, L.spec.row)
            local now = row and row.value
            local stat = rec and L.spec.kind == 'stat' and rec.stats[L.spec.stat]
            local moved = (now and now ~= L.value) or (stat and stat.mul ~= L.stat_mul)
            if moved and not lines.changed[L.key] then
                lines.changed[L.key] = true
                note(string.format('Line %s (%s): the live value changed (row %s, stat %s; was %s, stat %s): the line '
                                   .. 'keeps its number until the game restarts', L.key, L.spec.name, tostring(now),
                                   tostring(stat and stat.mul), tostring(L.value), tostring(L.stat_mul)))
            end
        end
    end
end

local function lines_describe()
    local n = {ours = 0, vanilla = 0, other = 0}
    for _, L in ipairs(lines.list) do
        if L.state == 'ours' then n.ours = n.ours + 1
        elseif L.state == 'vanilla' then n.vanilla = n.vanilla + 1
        else n.other = n.other + 1 end
    end
    return string.format('%s: %d lines (%d ours, %d the game\'s, %d other)%s', lines.state, #lines.list, n.ours,
                         n.vanilla, n.other, lines.why and (' (' .. lines.why .. ')') or '')
end

