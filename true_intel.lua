-- Native memory

local native = {}

local function init_native()
    -- Under the mod's own names, bound to kernel32's exports: every addon shares one FFI namespace, where a name keeps
    -- its first declaration, so another mod's ReadProcessMemory with other types must never be the one called.
    -- Declared one by one (a reload keeps the earlier declarations).
    for _, decl in ipairs({
        'void *ti_GetCurrentProcess(void) __asm__("GetCurrentProcess");',
        'void *ti_GetModuleHandleA(const char *name) __asm__("GetModuleHandleA");',
        'int ti_ReadProcessMemory(void *process, const void *address, void *buffer, size_t size, size_t *read) '
            .. '__asm__("ReadProcessMemory");',
        'int ti_WriteProcessMemory(void *process, void *address, const void *buffer, size_t size, size_t *written) '
            .. '__asm__("WriteProcessMemory");',
    }) do pcall(ffi.cdef, decl) end
    local ok, k32 = pcall(ffi.load, 'kernel32')
    if not ok then return false, 'kernel32 unavailable' end
    native.k32, native.process = k32, k32.ti_GetCurrentProcess()
    local game = k32.ti_GetModuleHandleA('game.dll')
    if game == nil then return false, 'game.dll not loaded' end
    native.base = tonumber(ffi.cast('uint64_t', game))
    return true
end

local function read(address, size)
    local buf, got = ffi.new('uint8_t[?]', size), ffi.new('size_t[1]')
    if native.k32.ti_ReadProcessMemory(native.process, ffi.cast('const void *', address), buf, size, got) == 0
       or tonumber(got[0]) ~= size then
        return nil
    end
    return ffi.string(buf, size)
end

-- The only writes: a row's text id (the passive records are private read-write memory: HD2Runtime's perk editor
-- writes the same rows' values). A refused write is logged and the line left the game's; nothing is ever unlocked.
local function write(address, bytes)
    local got = ffi.new('size_t[1]')
    local ok = native.k32.ti_WriteProcessMemory(native.process, ffi.cast('void *', address), bytes, #bytes, got)
    return ok ~= 0 and tonumber(got[0]) == #bytes
end

-- Plain Lua decoding (hd2-lua-mod skill 6.36: no FFI type punning in loops).
local function u32(blob, offset)
    offset = offset or 0
    if not blob or #blob < offset + 4 then return nil end
    local a, b, c, d = blob:byte(offset + 1, offset + 4)
    return a + 256 * b + 65536 * c + 16777216 * d
end

local function read32(address) return u32(read(address, 4)) end

local function pointer(blob, offset)
    offset = offset or 0
    local lo, hi = u32(blob, offset), u32(blob, offset + 4)
    if not (lo and hi) then return nil end
    local a = hi * 4294967296 + lo
    if a < 0x10000 or a >= 0x800000000000 then return nil end
    return a
end

local function read_pointer(address) return pointer(read(address, 8)) end

local function u32_bytes(v)
    v = v % 4294967296
    return string.char(v % 256, math.floor(v / 256) % 256, math.floor(v / 65536) % 256, math.floor(v / 16777216) % 256)
end

local function bits_to_f32(bits)
    local sign = 1
    if bits >= 2147483648 then sign = -1; bits = bits - 2147483648 end
    local exp = math.floor(bits / 8388608)
    local mant = bits - exp * 8388608
    if exp == 255 then return mant == 0 and sign * math.huge or 0 / 0 end
    if exp == 0 then return sign * mant * 2 ^ -149 end
    return sign * (1 + mant / 8388608) * 2 ^ (exp - 127)
end

local function f32(blob, offset)
    local b = u32(blob, offset)
    return b and bits_to_f32(b)
end

-- Known values both ways; a wrong decoder stops the mod before it writes anything.
local function float_selftest()
    local cases = {{0x3F800000, 1.0}, {0x3FCCCCCD, 1.6}, {0xBF800000, -1.0}, {0x3E800000, 0.25}, {0x42480000, 50}}
    for _, c in ipairs(cases) do
        if math.abs(bits_to_f32(c[1]) - c[2]) > 1e-6 then return false end
    end
    return u32(u32_bytes(0xDEADBEEF)) == 0xDEADBEEF
end

