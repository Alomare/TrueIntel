-- Resolution: signatures -> values

local code = nil  -- the signature engine
local V = {}      -- values read from the matched code (offsets; globals as rvas)
-- Every line needs the passive tables and the rows' layout; the armor lines also need the armor scale.
local REQUIRED = {'customization', 'passive_index', 'passives', 'rows', 'row_count', 'stat_rows', 'stat_row_count'}

local function finish_resolution()
    M.ready = true
    local found = {}
    for name in pairs(code.found) do found[#found + 1] = name end
    table.sort(found)
    for k, v in pairs(code.values) do V[k] = v end
    note('Signatures: found ' .. (#found > 0 and table.concat(found, ', ') or 'none'))
    for name, why in pairs(code.missing) do note('Signature ' .. name .. ' missing: ' .. tostring(why)) end
    for _, p in ipairs(code.problems or {}) do note('Signature problem: ' .. tostring(p)) end
    local missing = {}
    for _, k in ipairs(REQUIRED) do
        if not V[k] then missing[#missing + 1] = k end
    end
    return #missing == 0, table.concat(missing, ', ')
end

