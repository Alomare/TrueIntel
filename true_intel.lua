local log_file = open_log('TrueIntel.log')
local log_lines = 0

local function note(msg)
    if not log_file or log_lines >= LOG_LINES then return end
    log_lines = log_lines + 1
    pcall(function()
        log_file:write(string.format('[f%d t%.1f] %s\n', M.frames, M.time, msg))
        log_file:flush()
    end)
end

local once = {}
local function note_change(key, msg)  -- logs msg when it differs from the last one under key
    if once[key] == msg then return end
    once[key] = msg
    note(msg)
end

