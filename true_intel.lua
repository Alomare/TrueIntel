-- state: waiting (for the tables and texts), applied, text lost (our texts not registered: the game's back), failed,
-- idle (nothing to show), retired. list: every line made, {spec, row (address), value, number, values (text by
-- language), key, handle, id, state}.
local lines = {state = 'waiting', why = nil, retry_at = 0, tries = 0, rows_at = 0, text_at = 0, texts = nil,
               adapter = nil, text_misses = 0, text_lost_at = nil, list = {}, ours = {}, changed = {}, scale = nil}
